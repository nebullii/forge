"""Deterministic bootstrap scaffolds for supported local template families.

These scaffolds only create the structural skeleton for supported local builds.
They do not hardcode domain-specific business logic. The model still owns the
variable project work after bootstrap.
"""

from __future__ import annotations

import json
import re
from typing import Any


def scaffold_supported_task(task: dict, spec: str, decisions: dict) -> str | None:
    """Return deterministic bootstrap files for supported local setup tasks."""
    specialization = str(task.get("specialization", "")).strip().lower()
    if specialization != "setup":
        return None

    family = _template_family(decisions)
    title = _project_title(spec)
    styling = _stack_value(decisions, "styling")

    if family == "web-app":
        return _web_app_setup_response(title, styling=styling, spec=spec)
    if family == "api-only":
        return _api_only_setup_response(title, spec=spec)
    if family == "static-site":
        return _static_site_setup_response(title, spec=spec)
    return None


def scaffold_supported_spec_api_payload(task: dict, spec: str, decisions: dict) -> dict[str, Any] | None:
    """Return a strict Spec API payload for supported deterministic CRUD tasks."""
    family = _template_family(decisions)
    if family not in {"web-app", "api-only"}:
        return None

    specialization = str(task.get("specialization", "")).strip().lower()
    if specialization == "setup":
        deterministic = scaffold_supported_task(task, spec, decisions)
        if deterministic is None:
            return None
        files = _extract_file_blocks(deterministic)
        return _strict_payload(files, notes=["Generated by deterministic Forge setup scaffold."])

    spec_doc = _parse_spec_document(spec)
    if not spec_doc:
        return None

    if specialization == "backend":
        resource = _resource_for_task(task, spec_doc)
        if resource is None:
            return None
        model = _model_for_resource(resource, spec_doc)
        if model is None:
            return None
        files = _crud_backend_files(resource, model, spec)
        contracts = _crud_backend_contracts(resource, model)
        return _strict_payload(
            files,
            contracts=contracts,
            notes=["Generated by deterministic Forge CRUD backend scaffold."],
        )

    if specialization == "frontend" and family == "web-app":
        ui = _ui_for_task(task, spec_doc)
        if ui is None:
            return None
        resource = _resource_for_ui(ui, spec_doc)
        if resource is None:
            return None
        model = _model_for_resource(resource, spec_doc)
        if model is None:
            return None
        files = _crud_frontend_files(resource, model, spec)
        return _strict_payload(
            files,
            notes=["Generated by deterministic Forge CRUD frontend scaffold."],
        )

    if specialization == "test":
        test_case = _test_for_task(task, spec_doc)
        if test_case is None:
            return None
        resource = _resource_for_test(test_case, spec_doc)
        if resource is None:
            return None
        model = _model_for_resource(resource, spec_doc)
        if model is None:
            return None
        files = _crud_test_files(resource, model)
        return _strict_payload(
            files,
            notes=["Generated by deterministic Forge CRUD test scaffold."],
        )

    return None


def _template_family(decisions: dict) -> str:
    if not isinstance(decisions, dict):
        return ""
    family = str(decisions.get("template_family", "")).strip().lower()
    if family:
        return family

    stack = decisions.get("stack", {})
    framework = str(stack.get("framework", "")).strip().lower()
    frontend = str(stack.get("frontend", "")).strip().lower()

    if framework == "fastapi" and frontend == "react":
        return "web-app"
    if framework == "fastapi" and frontend in {"none", ""}:
        return "api-only"
    if framework == "static-html":
        return "static-site"
    return ""


def _stack_value(decisions: dict, key: str) -> str:
    if not isinstance(decisions, dict):
        return ""
    stack = decisions.get("stack", {})
    return str(stack.get(key, "")).strip().lower()


def _project_title(spec: str) -> str:
    match = re.search(r"^#\s*Project:\s*(.+)$", spec, re.MULTILINE)
    if match:
        return match.group(1).strip()
    return "Forge Project"


