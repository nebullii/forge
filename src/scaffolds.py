def _optional_schema_block(fields: dict[str, dict[str, Any]]) -> str:
    if not fields:
        return "    name: str | None = None"
    return "\n".join(
        f"    {name}: {_py_type(str(meta.get('type', 'string')))} | None = None"
        for name, meta in fields.items()
    )


def _crud_backend_contracts(resource, model) -> dict[str, list[dict[str, Any]]]:
    resource_name = resource.name
    model_name = model.name
    fields = {name: str(meta.get("type", "string")) for name, meta in _field_map(model).items()}
    actions = {str(item).lower() for item in resource.body.get("actions", [])}
    auth = "jwt" if str(resource.body.get("auth") or "").lower() == "required" else "none"
    api = []
    if "list" in actions:
        api.append({"method": "GET", "path": f"/api/{resource_name}", "response_schema": {"type": "array", "items": model_name}, "auth": auth})
    if "get" in actions:
        api.append({"method": "GET", "path": f"/api/{resource_name}/{{id}}", "response_schema": {"type": model_name}, "auth": auth})
    if "create" in actions:
        api.append({"method": "POST", "path": f"/api/{resource_name}", "request_schema": fields, "response_schema": {"type": model_name}, "auth": auth})
    if "update" in actions:
        api.append({"method": "PATCH", "path": f"/api/{resource_name}/{{id}}", "request_schema": fields, "response_schema": {"type": model_name}, "auth": auth})
    if "delete" in actions:
        api.append({"method": "DELETE", "path": f"/api/{resource_name}/{{id}}", "response_schema": {"status": "deleted"}, "auth": auth})
    return {
        "api": api,
        "models": [{"name": model_name, "fields": fields}],
        "events": [],
    }


