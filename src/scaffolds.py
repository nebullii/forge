def _example_payload(fields: dict[str, dict[str, Any]]) -> dict[str, Any]:
    if not fields:
        return {"name": "Acme Studio"}
    payload: dict[str, Any] = {}
    for name, meta in fields.items():
        field_type = str(meta.get("type", "string"))
        payload[name] = _example_value(name, field_type, updated=False)
    return payload


def _example_update_payload(fields: dict[str, dict[str, Any]]) -> dict[str, Any]:
    if not fields:
        return {"name": "Acme Studio Updated"}
    name, meta = next(iter(fields.items()))
    if "status" in fields:
        name, meta = "status", fields["status"]
    return {name: _example_value(name, str(meta.get("type", "string")), updated=True)}


def _example_value(name: str, field_type: str, updated: bool) -> Any:
    if field_type.startswith("enum[") and field_type.endswith("]"):
        options = [item.strip() for item in field_type[5:-1].split(",") if item.strip()]
        if not options:
            return "updated" if updated else "value"
        return options[min(1, len(options) - 1)] if updated else options[0]
    normalized = field_type.lower()
    if normalized == "email":
        return "updated@example.test" if updated else "ops@example.test"
    if normalized in {"integer", "int"}:
        return 2 if updated else 1
    if normalized in {"boolean", "bool"}:
        return bool(updated)
    if normalized in {"money", "float", "decimal"}:
        return 20.0 if updated else 10.0
    return f"{name.title()} Updated" if updated else "Acme Studio"


